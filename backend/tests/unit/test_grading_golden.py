"""Golden grading tables (P7.2). Each ``tests/fixtures/grading/*.json`` holds a scheme, papers, marks and
the expected results — worked out by hand (see each student's ``why``), never generated by the engine.

Expected strings with a decimal point must match exactly (they pin rounding and places); whole numbers
are compared by value (``"18"`` == ``18.0`` credits).
"""

from __future__ import annotations

import json
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest

from app.modules.grading.engine import (
    Attendance,
    Component,
    MarkInput,
    PaperSpec,
    assign_ranks,
    grade_exam,
    parse_config,
)

TABLES = sorted((Path(__file__).resolve().parent.parent / "fixtures" / "grading").glob("*.json"))


def _paper(p: dict[str, Any]) -> PaperSpec:
    return PaperSpec(
        p["id"],
        tuple(
            Component(c["code"], Decimal(c["max"]), Decimal(c["min_pass"]) if "min_pass" in c else None)
            for c in p["components"]
        ),
        credits=Decimal(p["credits"]) if "credits" in p else None,
        pass_total=Decimal(p["pass_total"]) if "pass_total" in p else None,
    )


def _marks(m: dict[str, Any]) -> MarkInput:
    values = {k: Decimal(v) for k, v in m.items() if k != "attendance"}
    return MarkInput(values, Attendance(m.get("attendance", "present")))


def _same(actual: Any, expected: Any) -> bool:
    if expected is None or actual is None:
        return actual is None and expected is None
    if isinstance(expected, list):
        return list(actual) == expected
    if hasattr(actual, "value"):  # enums
        return bool(actual.value == expected)
    if isinstance(actual, Decimal):
        return str(actual) == expected if "." in str(expected) else actual == Decimal(str(expected))
    return bool(actual == expected)


def _check(where: str, obj: Any, expected: dict[str, Any]) -> list[str]:
    return [
        f"{where}.{key}: expected {want!r}, got {getattr(obj, key)!r}"
        for key, want in expected.items()
        if key != "papers" and not _same(getattr(obj, key), want)
    ]


@pytest.mark.parametrize("path", TABLES, ids=lambda p: p.stem)
def test_golden_table(path: Path) -> None:
    table = json.loads(path.read_text(encoding="utf-8"))
    cfg = parse_config(table["config"])
    papers = [_paper(p) for p in table["papers"]]
    problems: list[str] = []
    results = {}
    for student in table["students"]:
        r = grade_exam(papers, {pid: _marks(m) for pid, m in student["marks"].items()}, cfg)
        results[student["id"]] = r
        expected = student["expected"]
        problems += _check(student["id"], r, expected)
        by_id = {p.paper_id: p for p in r.papers}
        for pid, want in expected.get("papers", {}).items():
            problems += _check(f"{student['id']}.{pid}", by_id[pid], want)
    for method, want_ranks in table.get("ranks", {}).items():
        got = assign_ranks(results, method)
        if got != want_ranks:
            problems.append(f"ranks[{method}]: expected {want_ranks}, got {got}")
    assert not problems, "\n".join(problems)


def test_corpus_is_present() -> None:
    assert {p.stem for p in TABLES} >= {"cbse_style_class10", "credit_10_point", "coaching_marks_only"}
